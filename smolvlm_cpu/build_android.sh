#!/usr/bin/env bash
set -euo pipefail

ROOT_DIR="/home/zzl/project4/execu-XNNPACK/executorch"
EXAMPLE_DIR="${ROOT_DIR}/smolvlm_cpu"
BUILD_DIR="${ROOT_DIR}/cmake-out-android-smolvlm-cpu"
PYTHON_BIN="/home/zzl/tools/conda/envs/executorch-XNNPACK/bin/python"

: "${ANDROID_NDK:=/home/zzl/project/AndroidNDK26}"

cd "${ROOT_DIR}"

cmake . \
  -DCMAKE_INSTALL_PREFIX="${BUILD_DIR}" \
  -DCMAKE_TOOLCHAIN_FILE="${ANDROID_NDK}/build/cmake/android.toolchain.cmake" \
  -DANDROID_SUPPORT_FLEXIBLE_PAGE_SIZES=ON \
  --preset "android-arm64-v8a" \
  -DANDROID_PLATFORM=android-28 \
  -DPYTHON_EXECUTABLE="${PYTHON_BIN}" \
  -DCMAKE_BUILD_TYPE=Release \
  -DEXECUTORCH_PAL_DEFAULT=posix \
  -DEXECUTORCH_BUILD_DEVTOOLS=OFF \
  -DEXECUTORCH_BUILD_ANDROID_JNI=OFF \
  -DEXECUTORCH_BUILD_CPUINFO=ON \
  -DEXECUTORCH_BUILD_PTHREADPOOL=ON \
  -DEXECUTORCH_BUILD_XNNPACK=OFF \
  -DEXECUTORCH_BUILD_EXTENSION_NAMED_DATA_MAP=ON \
  -DEXECUTORCH_BUILD_EXTENSION_DATA_LOADER=ON \
  -DEXECUTORCH_BUILD_EXTENSION_MODULE=ON \
  -DEXECUTORCH_BUILD_EXTENSION_TENSOR=ON \
  -DEXECUTORCH_BUILD_EXTENSION_LLM=ON \
  -DEXECUTORCH_BUILD_EXTENSION_LLM_RUNNER=ON \
  -DEXECUTORCH_BUILD_EXTENSION_RUNNER_UTIL=ON \
  -DEXECUTORCH_BUILD_EXTENSION_TRAINING=OFF \
  -DEXECUTORCH_BUILD_VULKAN=OFF \
  -DEXECUTORCH_BUILD_KERNELS_OPTIMIZED=ON \
  -DEXECUTORCH_BUILD_KERNELS_QUANTIZED=ON \
  -DEXECUTORCH_BUILD_KERNELS_LLM=ON \
  -DEXECUTORCH_BUILD_TESTS=OFF \
  -B "${BUILD_DIR}"

cmake --build "${BUILD_DIR}" -j"$(nproc)" --target install --config Release

cmake "${EXAMPLE_DIR}" \
  -DCMAKE_INSTALL_PREFIX="${BUILD_DIR}" \
  -DCMAKE_TOOLCHAIN_FILE="${ANDROID_NDK}/build/cmake/android.toolchain.cmake" \
  -DANDROID_SUPPORT_FLEXIBLE_PAGE_SIZES=ON \
  -DEXECUTORCH_ENABLE_LOGGING=ON \
  -DANDROID_ABI=arm64-v8a \
  -DANDROID_PLATFORM=android-28 \
  -DCMAKE_BUILD_TYPE=Release \
  -DPYTHON_EXECUTABLE="${PYTHON_BIN}" \
  -DEXECUTORCH_BUILD_CPUINFO=ON \
  -DEXECUTORCH_BUILD_PTHREADPOOL=ON \
  -DEXECUTORCH_BUILD_XNNPACK=OFF \
  -DEXECUTORCH_BUILD_KERNELS_OPTIMIZED=ON \
  -DEXECUTORCH_BUILD_KERNELS_QUANTIZED=ON \
  -DEXECUTORCH_BUILD_KERNELS_LLM=ON \
  -B "${BUILD_DIR}/smolvlm_cpu"

cmake --build "${BUILD_DIR}/smolvlm_cpu" -j"$(nproc)" --config Release

echo "built ${BUILD_DIR}/smolvlm_cpu/smolvlm_runner"
